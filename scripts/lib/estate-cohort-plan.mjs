/**
 * Cohort declaration generator (MC-CONFLUENCE-002 §8). Pure: governed estate sources + a recorded repository-facts
 * snapshot in, a deterministic plan out. It writes nothing and promotes nothing; the promotion gate stays the only authority.
 *
 * Everything a property needs that can be derived from existing facts is generated here once, instead of hand-patched per site:
 *   - the machine-health contract payload and a platform-appropriate route source that contains exactly the substrings the
 *     reviewed read-only profile checks for,
 *   - the health-target patch the sweep needs to verify that contract,
 *   - the registry `operating` verification declaration,
 *   - the per-property read-only profile (fixed argv, same shape as the AIAIMate profile) and its host-binding commands.
 * What cannot be derived (unknown platform, unknown deploy identity) is reported as a blocker, never guessed.
 */

import { createHash } from 'node:crypto';

export const COHORT_PLAN_SCHEMA = 'gfd-estate-cohort-plan-1';
export const VERIFICATION_PROFILE = 'gfd-property-health-production';
export const VERIFICATION_PREDICATE = 'Run the same configured health probe again and require this finding key to be absent.';

const slug = (propertyId) => propertyId.replace(/\.[a-z]+$/, '').replace(/[^a-z0-9]+/g, '-');

/** Detect the deploy platform from recorded repository markers only. */
export function detectPlatform(facts) {
  const m = facts?.markers || {};
  if (m.workerJs) return 'pages-advanced-worker';
  if (m.functionsDir) return 'pages-functions';
  if (m.nextConfig && m.srcDir) return m.nextStaticExport ? 'nextjs-static-export' : 'nextjs';
  return 'unknown';
}

const payloadLiteral = (propertyId, productId) => `{
  contract: 'gfd-property-health',
  contractVersion: 1,
  propertyId: '${propertyId}',
  productId: '${productId}',
  status: 'ok',
}`;

const HEADER = '// GFD machine-health contract (gfd-property-health v1). Generated by scripts/lib/estate-cohort-plan.mjs.';

const ROUTES = Object.freeze({
  'pages-functions': (propertyId, productId) => ({
    file: 'functions/api/gfd-property-health.js',
    publicPath: '/api/gfd-property-health',
    source: `${HEADER}
const payload = ${payloadLiteral(propertyId, productId)};

export function onRequestGet() {
  return new Response(JSON.stringify(payload), {
    status: 200,
    headers: { 'content-type': 'application/json', 'cache-control': 'no-store, max-age=0' },
  });
}
`,
  }),
  'nextjs-static-export': (propertyId, productId) => ({
    file: 'src/app/api/gfd-property-health/route.ts',
    publicPath: '/api/gfd-property-health',
    source: `${HEADER}
export const dynamic = 'force-static'; // next.config.js uses output: 'export'

const payload = ${payloadLiteral(propertyId, productId)};

export function GET() {
  return Response.json(payload, { status: 200 });
}
`,
  }),
  nextjs: (propertyId, productId) => ({
    file: 'src/app/api/gfd-property-health/route.ts',
    publicPath: '/api/gfd-property-health',
    source: `${HEADER}
export const dynamic = 'force-dynamic';

const payload = ${payloadLiteral(propertyId, productId)};

export function GET() {
  return Response.json(payload, { status: 200, headers: { 'cache-control': 'no-store, max-age=0' } });
}
`,
  }),
});

/** The platform-specific blockers that no generator can resolve. */
function platformBlockers(platform, operating) {
  const blockers = [];
  if (platform === 'unknown') blockers.push('deploy platform could not be established from repository markers; an operator must choose where the health route lives');
  if (platform === 'pages-advanced-worker') blockers.push('Pages advanced mode (_worker.js) ignores functions/: the contract route must be added inside the worker entry, not as a functions/ file');
  if (!operating?.deploy_identity?.provider || operating.deploy_identity.provider === 'unknown') blockers.push('registry deploy identity is unknown');
  return blockers;
}

export function profileArgv(routePath, propertyId) {
  const parts = routePath.split('/').map((part) => `'${part}'`).join(' / ');
  const check = 'import sys, pathlib;'
    + `p = pathlib.Path(sys.argv[1]) / ${parts};`
    + "t = p.read_text(encoding='utf-8');"
    + `ok = "contract: 'gfd-property-health'" in t and "propertyId: '${propertyId}'" in t;`
    + 'sys.exit(0 if ok else 1)';
  // The host selects its Python interpreter; the binder verifies that executable separately.
  return ['{python_executable}', '-B', '-c', check, '{repository_root}'];
}

export function profileArgvDigest(routePath, propertyId) {
  return `sha256:${createHash('sha256').update(JSON.stringify(profileArgv(routePath, propertyId))).digest('hex')}`;
}

export function buildCohortPlan({ registry, healthTargets, repoFacts, readinessReport, generatedAt }) {
  const plans = readinessReport.nextCohort.properties.map((readiness) => {
    const { propertyId } = readiness;
    const property = registry.properties.find((entry) => entry.id === propertyId);
    const operating = property.operating || {};
    const repository = operating.repository;
    const facts = repoFacts.repositories[repository] || null;
    const platform = detectPlatform(facts);
    const productId = property.brand_id || slug(propertyId);
    const route = ROUTES[platform]?.(propertyId, productId) || null;
    const target = (healthTargets.targets || []).find((entry) => entry.id === productId || entry.id === slug(propertyId));
    const profile = `web-health-readonly-${slug(propertyId)}-v1`;
    const contract = { contract: 'gfd-property-health', contractVersion: 1, propertyId, productId, status: 'ok' };
    const blockers = [
      ...(facts ? [] : ['no recorded repository facts']),
      ...(facts?.private ? ['repository is private: the host workspace needs authenticated clone access'] : []),
      ...platformBlockers(platform, operating),
      ...(route ? [] : ['no route template for this platform']),
      ...(target ? [] : ['no health target to attach the machine contract to']),
    ];
    return {
      propertyId,
      repository,
      repositoryAuthority: { known: Boolean(repository), source: operating.repository_source || 'estate/registry.json' },
      platform,
      machineHealthContract: {
        payload: contract,
        route: route ? { file: route.file, publicPath: route.publicPath, source: route.source } : null,
        healthTargetPatch: target && route
          ? { id: target.id, set: { sweepUrl: `https://${propertyId}${route.publicPath}`, expectedKeyword: 'gfd-property-health', machineContract: contract } }
          : null,
      },
      verificationDeclaration: {
        registryPatch: {
          id: propertyId,
          operating: {
            investigation_profile: profile,
            verification_profile: VERIFICATION_PROFILE,
            verification_scope: 'production',
            verification_predicate: VERIFICATION_PREDICATE,
          },
        },
      },
      readOnlyProfile: {
        name: profile,
        routePath: route?.file || null,
        argv: route ? profileArgv(route.file, propertyId) : null,
        argvDigest: route ? profileArgvDigest(route.file, propertyId) : null,
        shape: 'one fixed read-only argv, exit_nonzero_reproduces; no repair command, no credentials',
      },
      hostRegistration: route
        ? {
          operator: true,
          steps: [
            `git clone https://github.com/${repository}.git <workspace-root>   # clean clone; merge the generated route first`,
            ...['--apply', '--verify'].map((mode) => `python scripts/fwomps-property-host-binding.py --property ${propertyId} --repository ${repository} --workspace ${slug(propertyId)} --profile ${profile} --route-path ${route.file} --expected-argv-digest ${profileArgvDigest(route.file, propertyId)} --workspace-root <workspace-root> --result-origin https://goodflippindesign.com --worker-id fwomps-host-weave0-01 ${mode}`),
            `node --no-warnings scripts/property-promotion-gate.mjs --property ${propertyId} --fwomps-home ~/.fwomps`,
          ],
        }
        : null,
      missing: [...readiness.missing],
      blockers,
      order: [
        'merge the generated health route in the property repository',
        'apply the health-target patch and registry declaration in this repository',
        'confirm the sweep passes the new contract',
        'register the host profile (operator)',
        'promotion gate must report C1-C10 PASS and hostVerified',
      ],
    };
  });
  return {
    schema: COHORT_PLAN_SCHEMA,
    generatedAt,
    authority: { repair: false, deployment: false, promotion: false },
    note: 'Declarations only. Nothing here is applied; each property is promoted one at a time by the promotion gate.',
    properties: plans,
  };
}
